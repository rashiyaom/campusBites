// Function to seed all data to localStorage
export const seedAllBusinessData = () => {
  // Save partners
  const existingPartners = JSON.parse(localStorage.getItem('partners') || '[]');
  const newPartners = PARTNER_ACCOUNTS.filter(
    p => !existingPartners.some((ep: any) => ep.email === p.email)
  );
  localStorage.setItem('partners', JSON.stringify([...existingPartners, ...newPartners]));

  // Save businesses
  const existingBusinesses = JSON.parse(localStorage.getItem('businesses') || '[]');
  const newBusinesses = BUSINESSES.filter(
    b => !existingBusinesses.some((eb: any) => eb.id === b.id)
  );
  localStorage.setItem('businesses', JSON.stringify([...existingBusinesses, ...newBusinesses]));

  // Also save as cafeterias for backward compatibility
  const existingCafeterias = JSON.parse(localStorage.getItem('cafeterias') || '[]');
  const cafeteriaFormat = BUSINESSES.map(b => ({
    id: b.id,
    name: b.name,
    description: b.description,
    image: b.image,
    rating: b.rating,
    location: b.location,
    isOpen: b.isOpen,
    openingTime: b.openTime,
    closingTime: b.closeTime,
  }));
  const newCafeterias = cafeteriaFormat.filter(
    c => !existingCafeterias.some((ec: any) => ec.id === c.id)
  );
  localStorage.setItem('cafeterias', JSON.stringify([...existingCafeterias, ...newCafeterias]));

  // Save products
  const existingProducts = JSON.parse(localStorage.getItem('products') || '[]');
  const newProducts = SAMPLE_PRODUCTS.filter(
    p => !existingProducts.some((ep: any) => ep.id === p.id)
  );
  localStorage.setItem('products', JSON.stringify([...existingProducts, ...newProducts]));

  // Trigger storage event
  window.dispatchEvent(new Event('storage'));

  return {
    partnersAdded: newPartners.length,
    businessesAdded: newBusinesses.length,
    productsAdded: newProducts.length,
  };
};

// Get credentials info for display
export const getCredentialsInfo = () => {
  return PARTNER_ACCOUNTS.map(p => ({
    businessName: p.businessName,
    businessType: p.businessType,
    email: p.email,
    password: p.password,
  }));
};
